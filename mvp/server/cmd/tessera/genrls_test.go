func runCLI(t *testing.T, args ...string) (string, error) {
	t.Helper()
	var out, errOut bytes.Buffer
	err := run(context.Background(), args, &out, &errOut)
	return out.String() + errOut.String(), err
}

// TestGenRLS: `tessera admin gen-rls` needs no database or environment, prints
// the row-level-security file, writes it with -out, and -check agrees that the
// embedded rls.sql is what it renders.
func TestGenRLS(t *testing.T) {
	t.Setenv("TESSERA_ENV", "")
	out, err := runCLI(t, "admin", "gen-rls")
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"Code generated by `tessera admin gen-rls`; DO NOT EDIT.",
		"ALTER TABLE identities ENABLE ROW LEVEL SECURITY;",
		"ALTER TABLE identities FORCE ROW LEVEL SECURITY;",
		"CREATE POLICY tenant_isolation ON identities",
		"USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), ''))",
		"WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), ''))",
		"CREATE POLICY lookup_by_hash ON sessions FOR SELECT",
		"current_setting('app.lookup', true) = 'session_hash'",
		"CREATE POLICY lookup_by_hash ON login_transactions FOR SELECT",
		"current_setting('app.lookup', true) = 'login_cookie_hash'",
		"ALTER TABLE audit_events FORCE ROW LEVEL SECURITY;",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("output lacks %q", want)
		}
	}
	for _, global := range store.GlobalTables {
		if strings.Contains(out, "ALTER TABLE "+global+" ") {
			t.Errorf("global table %s has row-level security", global)
		}
	}
	if n := strings.Count(out, "CREATE POLICY lookup_by_hash"); n != 2 {
		t.Errorf("%d lookup policies, want 2", n)
	}
	// deterministic
	again, err := runCLI(t, "admin", "gen-rls")
	if err != nil || again != out {
		t.Errorf("second run differs (%v)", err)
	}
	file := filepath.Join(t.TempDir(), "rls.sql")
	if msg, err := runCLI(t, "admin", "gen-rls", "-out", file); err != nil || !strings.Contains(msg, "wrote") {
		t.Fatalf("-out: %q %v", msg, err)
	}
	if b, err := os.ReadFile(file); err != nil || string(b) != out {
		t.Errorf("-out file differs from stdout (%v)", err)
	}
	if msg, err := runCLI(t, "admin", "gen-rls", "-check"); err != nil || !strings.Contains(msg, "up to date") {
		t.Errorf("-check: %q %v (internal/store/schema/postgres/rls.sql must be regenerated)", msg, err)
	}
	if _, err := runCLI(t, "admin", "gen-rls", "extra"); err == nil {
		t.Error("stray argument accepted")
	}
}

// TestAdminOnTestTarget runs the operator CLI against the test database
// target: a SQLite file, or with TESSERA_TEST_PG_URL a Postgres DSN (the whole
// path: DSN flag, migrations as the owner, requests as tessera_app).
func TestAdminOnTestTarget(t *testing.T) {
	t.Setenv("TESSERA_ENV", "dev")
	t.Setenv("TESSERA_PUBLIC_URL", "http://localhost:5173")
	t.Setenv("TESSERA_KEK", base64.StdEncoding.EncodeToString([]byte("0123456789abcdef0123456789abcdef")))
	t.Setenv("USER", "op-pat")
	db := store.TestTarget(t)
	msg, err := adminRun(t, db, "create-tenant", "-slug", "pgco", "-name", "PG Co")
	if err != nil || !strings.Contains(msg, "created tenant pgco") {
		t.Fatalf("create-tenant: %q %v", msg, err)
	}
	if msg, err := adminRun(t, db, "create-tenant", "-slug", "pgco", "-name", "again"); err == nil {
		t.Errorf("duplicate slug accepted: %q", msg)
	}
	if strings.Contains(msg, "postgres://") {
		t.Errorf("output echoes the DSN: %q", msg)
	}
	st, err := store.Open(context.Background(), db)
	if err != nil {
		t.Fatal(err)
	}
	defer st.Close()
	ts, err := st.ActiveTenants(context.Background())
	if err != nil || len(ts) != 1 || ts[0].Slug != "pgco" {
		t.Fatalf("tenants %+v %v", ts, err)
	}
	var actions []string
	if err := st.ReadTenant(context.Background(), ts[0].ID, func(tx *store.TenantTx) error {
		evs, err := tx.AuditLog(-1)
		for _, e := range evs {
			actions = append(actions, e.Action)
		}
		return err
	}); err != nil {
		t.Fatal(err)
	}
	if strings.Join(actions, ",") != "tenant.created" {
		t.Errorf("audit events %v, want tenant.created", actions)
	}
}
