// DB owns the database handle. The *sql.DB is unexported and there is no
// accessor: no other package can obtain a *sql.DB, *sql.Tx or *sql.Conn.
//
// Writes are serialized through one mutex so SQLite never sees two concurrent
// writers; read-only tenant transactions (ReadTenant) run concurrently (WAL).
type DB struct {
	sql   *sql.DB // the application pool
	owner *sql.DB // Postgres: the migration role's pool (equal to sql when there is no separate request pool)
	d     dialect
	mu    sync.Mutex
	stmts stmtCache // prepared statements (SQLite only; see stmtFor)

	schemaMu sync.Mutex // SchemaCurrent's remembered pass
	schemaOK bool

	leaderOnce sync.Once // LeaderLocker
	leader     *LeaderLocker
}

// writeLock serializes writers on SQLite (one writer at a time); Postgres
// serializes through its own locks, so it takes none. Use as
// `defer d.writeLock()()`.
func (d *DB) writeLock() func() {
	if d.d == dialectPostgres {
		return func() {}
	}
	start := time.Now()
	d.mu.Lock()
	obs.DBLockWait.Observe(time.Since(start).Seconds())
	return d.mu.Unlock
}

// Open opens (creating if needed) the database at path and applies the schema.
// A database created before tenancy is refused with ErrLegacySchema. A
// postgres:// DSN opens Postgres instead of a SQLite file.
func Open(ctx context.Context, path string) (*DB, error) { return open(ctx, path, false, nil) }

// OpenApp is Open for a process that serves requests. On Postgres the request
// pool is the application login in app.DSN, and the open fails when its
// session_user could undo row-level security (see CheckAppRole). On SQLite it
// is Open.
func OpenApp(ctx context.Context, path string, app AppOptions) (*DB, error) {
	return open(ctx, path, false, &app)
}

// OpenFresh opens the database at path and drops every table before applying
// the schema, so seeding always starts empty. It works on a database left from
// an older schema (including one that predates tenancy) without deleting any
// file, so a mistyped path can never destroy something that is not ours.
func OpenFresh(ctx context.Context, path string) (*DB, error) { return open(ctx, path, true, nil) }

func open(ctx context.Context, path string, fresh bool, app *AppOptions) (*DB, error) {
	if IsPostgresDSN(path) {
		if dsn := testAppDSN(path); dsn != "" { // test binaries only
			switch {
			case app == nil:
				app = &AppOptions{DSN: dsn}
			case app.DSN == "":
				c := *app
				c.DSN = dsn
				app = &c
			}
		}
		return openPostgres(ctx, path, fresh, app)
	}
	q := url.Values{}
	q.Add("_pragma", "busy_timeout(10000)")
	q.Add("_pragma", "journal_mode(WAL)")
	q.Add("_pragma", "synchronous(NORMAL)")
	// Write transactions start with BEGIN IMMEDIATE (the driver leaves
	// read-only ones deferred). A deferred write transaction that reads first
	// (InTenant checks the tenant) and then writes must upgrade its WAL
	// snapshot; if another handle on the file committed meanwhile, SQLite
	// returns SQLITE_BUSY at once and busy_timeout does not apply (#126). The
	// mutex below only serializes writers within one handle.
	q.Set("_txlock", "immediate")
	db, err := sql.Open("sqlite", "file:"+path+"?"+q.Encode())
	if err != nil {
		return nil, fmt.Errorf("store: open: %w", err)
	}
	db.SetMaxOpenConns(8)
	d := &DB{sql: db}
	if err := d.Migrate(ctx, fresh); err != nil {
		_ = db.Close()
		return nil, err
	}
	return d, nil
}

// Close closes the database.
func (d *DB) Close() error {
	if d.leader != nil {
		d.leader.Close()
	}
	d.stmts.close()
	err := d.sql.Close()
	if d.owner != nil && d.owner != d.sql {
		err = errors.Join(err, d.owner.Close())
	}
	return err
}

// Checkpoint truncates the write-ahead log into the main database file, so the
// file can be copied on its own (test fixtures). It does nothing on Postgres.
func (d *DB) Checkpoint(ctx context.Context) error {
	if d.d == dialectPostgres {
		return nil
	}
	_, err := d.sql.ExecContext(ctx, "PRAGMA wal_checkpoint(TRUNCATE)")
	return err
}

// ErrSnapshotUnsupported is returned by Snapshot on Postgres: tessera backup
// is SQLite-only for now (back up Postgres with pg_dump or the managed
// service's snapshots; see docs/runbooks/disaster-recovery.md).
var ErrSnapshotUnsupported = errors.New("store: snapshot is SQLite-only; back up Postgres with pg_dump or your provider's snapshots")

// IsPostgres reports whether the store runs on Postgres.
func (d *DB) IsPostgres() bool { return d.d == dialectPostgres }

// Snapshot writes a transactionally consistent copy of the whole database to
// path with VACUUM INTO, while the server keeps serving. path must not exist.
func (d *DB) Snapshot(ctx context.Context, path string) error {
	if d.d == dialectPostgres {
		return ErrSnapshotUnsupported
	}
	if _, err := d.sql.ExecContext(ctx, "VACUUM INTO ?", path); err != nil {
		return fmt.Errorf("store: snapshot: %w", err)
	}
	return nil
}

// Migrate creates the schema and the reserved _platform tenant; drop=true
// drops every table first (reseed). A database created before tenancy is
// refused with ErrLegacySchema unless drop is set.
func (d *DB) Migrate(ctx context.Context, drop bool) error {
	if d.d == dialectPostgres {
		return d.migratePG(ctx, drop)
	}
	d.mu.Lock()
	defer d.mu.Unlock()
	if drop {
		rev := slices.Clone(tables)
		slices.Reverse(rev)
		for _, t := range slices.Concat(legacyTables, rev) {
			// t comes from the fixed list above, never from input.
			if _, err := d.sql.ExecContext(ctx, "DROP TABLE IF EXISTS "+t); err != nil { // #nosec G202 -- fixed table names
				return fmt.Errorf("store: drop %s: %w", t, err)
			}
		}
	} else if legacy, err := d.legacySchema(ctx); err != nil {
		return err
	} else if legacy {
		return ErrLegacySchema
	}
	if err := d.upgradeLoginTxnPurpose(ctx); err != nil {
		return err
	}
	if err := d.upgradeProvTargetKinds(ctx); err != nil {
		return err
	}
	if err := d.upgradeAgentJobs(ctx); err != nil {
		return err
	}
	if err := d.upgradeSiemSinks(ctx); err != nil {
		return err
	}
	if err := d.upgradeUserIDColumns(ctx); err != nil {
		return err
	}
	if err := d.upgradeAdminChangeTypes(ctx); err != nil {
		return err
	}
	if err := d.upgradeCertTrust(ctx); err != nil {
		return err
	}
	if err := d.upgradeGrpInboxKinds(ctx); err != nil {
		return err
	}
	if err := d.upgradeSecurityControls(ctx); err != nil {
		return err
	}
	files, err := fs.Glob(schemaFS, "schema/*.sql")
	if err != nil {
		return err
	}
	slices.Sort(files)
	for _, f := range files {
		ddl, err := schemaFS.ReadFile(f)
		if err != nil {
			return err
		}
		if _, err := d.sql.ExecContext(ctx, string(ddl)); err != nil {
			return fmt.Errorf("store: schema %s: %w", f, err)
		}
	}
	return d.inSystemLocked(ctx, "migrate: ensure _platform tenant", func(s *SystemTx) error {
		_, err := s.exec(tenantsEnsurePlatform, sql.Named("id", tenancy.Platform.String()),
			sql.Named("created_at", T(nowUTC())))
		return err
	})
}

