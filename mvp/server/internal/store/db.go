// upgradeProvTargetKinds lets a SQLite database created before the vault and ERP target
// kinds (issue #304), the generic REST kind (issue #552), the database kind (issue #553), Salesforce
// (issue #555) or ServiceNow and Atlassian (issue #559) take them. CREATE TABLE IF NOT EXISTS cannot change a CHECK, and the table holds sealed credentials
// that must survive, so it is rebuilt: the new table is made from the old definition with the
// wider list, the rows are copied, the old table (with its index and triggers, which the schema
// run recreates) is dropped, and the new one takes its name. Postgres does this in migrations
// 0601, 0850, 0860, 0890 and 0930.
func (d *DB) upgradeProvTargetKinds(ctx context.Context) error {
	const wider = "CHECK (kind IN ('scim','okta','fake','cyberark','delinea','beyondtrust','sap','oracle','rest','sql','salesforce','servicenow','atlassian'))"
	// every earlier list a database may still hold
	olds := []string{"CHECK (kind IN ('scim','okta','fake'))",
		"CHECK (kind IN ('scim','okta','fake','cyberark','delinea','beyondtrust','sap','oracle'))",
		"CHECK (kind IN ('scim','okta','fake','cyberark','delinea','beyondtrust','sap','oracle','rest'))",
		"CHECK (kind IN ('scim','okta','fake','cyberark','delinea','beyondtrust','sap','oracle','sql'))",
		"CHECK (kind IN ('scim','okta','fake','cyberark','delinea','beyondtrust','sap','oracle','rest','sql'))",
		"CHECK (kind IN ('scim','okta','fake','cyberark','delinea','beyondtrust','sap','oracle','rest','sql','salesforce'))"}
	var ddl string
	err := d.sql.QueryRowContext(ctx, `SELECT sql FROM sqlite_master WHERE type = 'table' AND name = 'provisioning_targets'`).Scan(&ddl)
	if errors.Is(err, sql.ErrNoRows) {
		return nil
	}
	if err != nil {
		return err
	}
	old := ""
	for _, o := range olds {
		if strings.Contains(ddl, o) {
			old = o
		}
	}
	if old == "" {
		return nil
	}
	tx, err := d.sql.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback() }()
	newDDL := strings.Replace(strings.Replace(ddl, old, wider, 1), "provisioning_targets", "provisioning_targets__new", 1)
	for _, q := range []string{newDDL,
		"INSERT INTO provisioning_targets__new SELECT * FROM provisioning_targets",
		"DROP TABLE provisioning_targets",
		"ALTER TABLE provisioning_targets__new RENAME TO provisioning_targets"} {
		if _, err := tx.ExecContext(ctx, q); err != nil { // #nosec G202 -- fixed statements and the table's own stored definition
			return fmt.Errorf("store: upgrade provisioning_targets: %w", err)
		}
	}
	return tx.Commit()
}

// upgradeUserIDColumns adds the platform-user-id columns of issue #425 to a SQLite database created
// before them (CREATE TABLE IF NOT EXISTS cannot). Postgres does this in migrations 0531 and 0532.
func (d *DB) upgradeUserIDColumns(ctx context.Context) error {
	for _, c := range []struct{ table, column string }{
		{"identity_disables", "disabled_by_user_id"}, {"readiness_attestations", "actor_user_id"},
		{"grp_groups", "deleted_by_user_id"}, {"grp_groups", "deleted_by_display"}, {"grp_groups", "deleted_at"},
		{"grp_groups", "deleted_reason"}, {"grp_groups", "deleted_with_folder"},
	} {
		var exists, n int
		if err := d.sql.QueryRowContext(ctx,
			`SELECT count(*) FROM sqlite_master WHERE type = 'table' AND name = ?`, c.table).Scan(&exists); err != nil {
			return err
		}
		if err := d.sql.QueryRowContext(ctx,
			`SELECT count(*) FROM pragma_table_info(?) WHERE name = ?`, c.table, c.column).Scan(&n); err != nil {
			return err
		}
		if exists == 1 && n == 0 {
			// c comes from the fixed list above, never from input.
			if _, err := d.sql.ExecContext(ctx, "ALTER TABLE "+c.table+" ADD COLUMN "+c.column+" TEXT"); err != nil { // #nosec G202 -- fixed names
				return fmt.Errorf("store: upgrade %s: %w", c.table, err)
			}
		}
	}
	return nil
}

// legacySchema reports whether the database was created by an older server:
// identities without tenant_id (before tenancy), or access_requests without
// requested_by_user_id (before sign-in, PR5). CREATE TABLE IF NOT EXISTS
// cannot add those columns, and the old rows have no platform users.
func (d *DB) legacySchema(ctx context.Context) (bool, error) {
	for _, c := range []struct{ table, column string }{
		{"identities", "tenant_id"}, {"access_requests", "requested_by_user_id"},
	} {
		var exists, n int
		if err := d.sql.QueryRowContext(ctx,
			`SELECT count(*) FROM sqlite_master WHERE type = 'table' AND name = ?`, c.table).Scan(&exists); err != nil {
			return false, err
		}
		if err := d.sql.QueryRowContext(ctx,
			`SELECT count(*) FROM pragma_table_info(?) WHERE name = ?`, c.table, c.column).Scan(&n); err != nil {
			return false, err
		}
		if exists == 1 && n == 0 {
			return true, nil
		}
	}
	// admin_change_requests from before break-glass (PR13) has a type CHECK
	// that refuses breakglass.*, and SQLite cannot widen a CHECK in place.
	var def sql.NullString
	err := d.sql.QueryRowContext(ctx,
		`SELECT sql FROM sqlite_master WHERE type = 'table' AND name = 'admin_change_requests'`).Scan(&def)
	if err != nil && !errors.Is(err, sql.ErrNoRows) {
		return false, err
	}
	return def.Valid && !strings.Contains(def.String, "breakglass.register"), nil
}

// InTenant runs fn in one write transaction scoped to t. A zero tenancy.ID or
// an unknown tenant returns ErrNoTenant (and a zero id also records a
// tenancy.context_missing event in the _platform tenant). fn's error, or a
// panic, rolls the transaction back.
func (d *DB) InTenant(ctx context.Context, t tenancy.ID, fn func(*TenantTx) error) error {
	if t.IsZero() {
		d.RecordContextMissing(ctx, "store.InTenant called with the zero tenant id")
		return ErrNoTenant
	}
	defer d.writeLock()()
	return d.inTenant(ctx, t, false, fn)
}

// ReadTenant runs fn in one read-only transaction scoped to t: a consistent
// snapshot that runs concurrently with other readers. Writes through it fail
// with ErrReadOnly. Do not start another transaction inside fn.
func (d *DB) ReadTenant(ctx context.Context, t tenancy.ID, fn func(*TenantTx) error) error {
	if t.IsZero() {
		d.RecordContextMissing(ctx, "store.ReadTenant called with the zero tenant id")
		return ErrNoTenant
	}
	return d.inTenant(ctx, t, true, fn)
}

func (d *DB) inTenant(ctx context.Context, t tenancy.ID, readOnly bool, fn func(*TenantTx) error) (err error) {
	return d.inTenantOn(ctx, d.sql, t, readOnly, fn)
}

// inTenantOn is inTenant on a given pool (the application pool, or the owner
// pool for the test-only audit tamper handle).
func (d *DB) inTenantOn(ctx context.Context, pool *sql.DB, t tenancy.ID, readOnly bool, fn func(*TenantTx) error) (err error) {
	kind := "tenant_write"
	if readOnly {
		kind = "tenant_read"
	}
	start := time.Now()
	defer func() { d.observeTx(kind, start, err) }() // runs after the commit below, so err is final
	raw, err := pool.BeginTx(ctx, &sql.TxOptions{ReadOnly: readOnly})
	if err != nil {
		return fmt.Errorf("store: begin: %w", err)
	}
	sqltx := &xtx{tx: raw, d: d.d}
	if d.d == dialectPostgres {
		// Transaction-local (is_local = true): a pooled connection can never
		// carry the tenant into its next transaction. Row-level security reads
		// this setting; with it unset, no tenant row matches (fail closed).
		if _, err := raw.ExecContext(ctx, pgSetTenant, t.String()); err != nil {
			_ = raw.Rollback()
			return fmt.Errorf("store: set tenant: %w", err)
		}
		if !readOnly {
			// SQLite runs one writer at a time, and the store's code (the
			// readiness state machine, the audit chain head) is written for
			// that. On Postgres writers of one tenant queue on a transaction-
			// scoped advisory lock instead: no deadlocks or unique-key races
			// between two requests of a tenant, while other tenants and all
			// readers run in parallel.
			if _, err := raw.ExecContext(ctx, pgLockTenant, t.String()); err != nil {
				_ = raw.Rollback()
				return fmt.Errorf("store: lock tenant: %w", err)
			}
		}
	}
	ttx := &TenantTx{ctx: ctx, db: d, tx: sqltx, tenant: t, readOnly: readOnly}
	defer func() {
		if p := recover(); p != nil {
			_ = sqltx.Rollback()
			panic(p)
		}
		if err != nil {
			_ = sqltx.Rollback()
			return
		}
		if err = sqltx.Commit(); err == nil && ttx.appended > 0 {
			if ac, ok := AuditContextFrom(ctx); ok && ac.Committed != nil {
				ac.Committed.Add(ttx.appended)
			}
		}
	}()
	// The tenant must exist: every tenant_id this transaction writes then
	// references a tenants row (SQLite foreign keys are not enforced yet).
	var n int
	if err := sqltx.QueryRowContext(ctx, tenantsExists.sql, sql.Named("id", t.String())).Scan(&n); err != nil {
		return err
	}
	if n != 1 {
		return fmt.Errorf("%w: unknown tenant %s", ErrNoTenant, t)
	}
	return fn(ttx)
}

// InSystem runs fn in one write transaction that can touch only the
// GlobalTables. reason says why (it is for logs and audit later; it must not
// be empty).
func (d *DB) InSystem(ctx context.Context, reason string, fn func(*SystemTx) error) error {
	if reason == "" {
		return errors.New("store: InSystem needs a reason")
	}
	defer d.writeLock()()
	return d.inSystemLocked(ctx, reason, fn)
}

func (d *DB) inSystemLocked(ctx context.Context, reason string, fn func(*SystemTx) error) (err error) {
	start := time.Now()
	defer func() { d.observeTx("system_write", start, err) }()
	raw, err := d.sql.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("store: begin: %w", err)
	}
	sqltx := &xtx{tx: raw, d: d.d}
	defer func() {
		if p := recover(); p != nil {
			_ = sqltx.Rollback()
			panic(p)
		}
		if err != nil {
			_ = sqltx.Rollback()
			return
		}
		err = sqltx.Commit()
	}()
	return fn(&SystemTx{ctx: ctx, db: d, tx: sqltx, reason: reason})
}

// ReadSystem runs fn in one read-only system transaction. It does not take
// the write lock, so the per-request session lookup (§14.2) runs concurrently
// with other readers. Writes through it fail.
func (d *DB) ReadSystem(ctx context.Context, reason string, fn func(*SystemTx) error) (err error) {
	if reason == "" {
		return errors.New("store: ReadSystem needs a reason")
	}
	start := time.Now()
	defer func() { d.observeTx("system_read", start, err) }()
	raw, err := d.sql.BeginTx(ctx, &sql.TxOptions{ReadOnly: true})
	if err != nil {
		return fmt.Errorf("store: begin: %w", err)
	}
	sqltx := &xtx{tx: raw, d: d.d}
	defer func() {
		if p := recover(); p != nil {
			_ = sqltx.Rollback()
			panic(p)
		}
		if err != nil {
			_ = sqltx.Rollback()
			return
		}
		err = sqltx.Commit()
	}()
	return fn(&SystemTx{ctx: ctx, db: d, tx: sqltx, reason: reason})
}

// ForEachActiveTenant lists the active tenants (not _platform) in a SystemTx,
// then calls fn for each one inside its own InTenant transaction. An error in
// one tenant does not stop the others; all errors are returned joined.
// Background jobs use only this.
func (d *DB) ForEachActiveTenant(ctx context.Context, fn func(context.Context, *TenantTx) error) error {
	var active []Tenant
	if err := d.InSystem(ctx, "for each active tenant", func(s *SystemTx) error {
		var err error
		active, err = s.ActiveTenants()
		return err
	}); err != nil {
		return err
	}
	var errs []error
	for _, t := range active {
		if err := ctx.Err(); err != nil {
			return errors.Join(append(errs, err)...)
		}
		if err := d.InTenant(ctx, t.ID, func(tx *TenantTx) error { return fn(ctx, tx) }); err != nil {
			errs = append(errs, fmt.Errorf("tenant %s: %w", t.Slug, err))
		}
	}
	return errors.Join(errs...)
}

// ActiveTenants lists the active tenants (not _platform), ordered by slug.
func (d *DB) ActiveTenants(ctx context.Context) ([]Tenant, error) {
	var out []Tenant
	err := d.InSystem(ctx, "list active tenants", func(s *SystemTx) error {
		var err error
		out, err = s.ActiveTenants()
		return err
	})
	return out, err
}

// RecordContextMissing writes a tenancy.context_missing event to the
// _platform tenant. It is best effort: it never fails the caller, who is
// already failing closed.
func (d *DB) RecordContextMissing(ctx context.Context, where string) {
	_ = d.InTenant(context.WithoutCancel(ctx), tenancy.Platform, func(tx *TenantTx) error {
		return tx.Audit(nowUTC(), "system", "tenancy.context_missing", detailWhere(where))
	})
}
