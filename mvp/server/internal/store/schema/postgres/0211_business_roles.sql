CREATE TABLE business_roles (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  owner_identity_id BIGINT,
  risk TEXT NOT NULL DEFAULT 'low' CHECK (risk IN ('low','medium','high')),
  requestable BIGINT NOT NULL DEFAULT 0,
  birthright TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','retired')),
  version BIGINT NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_by TEXT,
  updated_at TEXT NOT NULL,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, name),
  FOREIGN KEY (tenant_id, owner_identity_id) REFERENCES identities (tenant_id, id)
);

CREATE TABLE business_role_entitlements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  role_id TEXT NOT NULL,
  group_id BIGINT NOT NULL,
  UNIQUE (tenant_id, role_id, group_id),
  FOREIGN KEY (tenant_id, role_id) REFERENCES business_roles (tenant_id, id),
  FOREIGN KEY (tenant_id, group_id) REFERENCES groups (tenant_id, id)
);

CREATE INDEX ix_role_entitlements_tenant_group ON business_role_entitlements (tenant_id, group_id);

CREATE TABLE business_role_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  role_id TEXT NOT NULL,
  version BIGINT NOT NULL,
  snapshot TEXT NOT NULL,
  note TEXT,
  changed_by TEXT,
  actor TEXT NOT NULL,
  changed_at TEXT NOT NULL,
  UNIQUE (tenant_id, role_id, version),
  FOREIGN KEY (tenant_id, role_id) REFERENCES business_roles (tenant_id, id)
);

CREATE TABLE business_role_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  role_id TEXT NOT NULL,
  identity_id BIGINT NOT NULL,
  source TEXT NOT NULL CHECK (source IN ('rule','request','manual')),
  assigned_by TEXT,
  assigned_at TEXT NOT NULL,
  request_id TEXT,
  UNIQUE (tenant_id, role_id, identity_id),
  FOREIGN KEY (tenant_id, role_id) REFERENCES business_roles (tenant_id, id),
  FOREIGN KEY (tenant_id, identity_id) REFERENCES identities (tenant_id, id)
);

CREATE INDEX ix_role_members_tenant_identity ON business_role_members (tenant_id, identity_id);

CREATE TABLE business_role_requests (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  role_id TEXT NOT NULL,
  beneficiary_id BIGINT NOT NULL,
  requested_by TEXT NOT NULL,
  justification TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('pending','approved','denied','cancelled')),
  requested_at TEXT NOT NULL,
  decided_by TEXT,
  decided_at TEXT,
  decision_reason TEXT,
  FOREIGN KEY (tenant_id, role_id) REFERENCES business_roles (tenant_id, id),
  FOREIGN KEY (tenant_id, beneficiary_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, requested_by) REFERENCES platform_users (tenant_id, id)
);

CREATE INDEX ix_role_requests_tenant_status ON business_role_requests (tenant_id, status);
CREATE UNIQUE INDEX ux_role_requests_pending ON business_role_requests (tenant_id, role_id, beneficiary_id)
  WHERE status = 'pending';

CREATE TRIGGER business_role_versions_no_update BEFORE UPDATE ON business_role_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('business_role_versions is append-only');

CREATE TRIGGER business_role_versions_no_delete BEFORE DELETE ON business_role_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('business_role_versions is append-only');

-- Columns that name a user (or an edge that may expire) but are not foreign keys: SQLite never
-- enforced them, and they hold display strings or ids of rows that may be gone. The guard refuses an
-- id that belongs to ANOTHER tenant and tolerates one that does not exist (tessera_guard_soft_ref).
CREATE TRIGGER tg_business_roles_updated_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, updated_by ON business_roles
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'updated_by', 'text');
CREATE TRIGGER tg_business_role_versions_changed_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, changed_by ON business_role_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'changed_by', 'text');
CREATE TRIGGER tg_business_role_members_assigned_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, assigned_by ON business_role_members
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'assigned_by', 'text');
CREATE TRIGGER tg_business_role_requests_decided_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, decided_by ON business_role_requests
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'decided_by', 'text');
