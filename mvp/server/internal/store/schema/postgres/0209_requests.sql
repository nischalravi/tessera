CREATE TABLE catalog_items (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  group_id BIGINT NOT NULL,
  requestable BIGINT NOT NULL DEFAULT 1,
  description TEXT NOT NULL DEFAULT '',
  owner_identity_id BIGINT,
  risk TEXT NOT NULL DEFAULT 'low' CHECK (risk IN ('low','medium','high')),
  eligible_types TEXT NOT NULL DEFAULT '[]',
  eligible_departments TEXT NOT NULL DEFAULT '[]',
  default_hours DOUBLE PRECISION CHECK (default_hours IS NULL OR default_hours > 0),
  max_hours DOUBLE PRECISION CHECK (max_hours IS NULL OR max_hours > 0),
  updated_by TEXT,
  updated_at TEXT NOT NULL,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, group_id),
  FOREIGN KEY (tenant_id, group_id) REFERENCES groups (tenant_id, id),
  FOREIGN KEY (tenant_id, owner_identity_id) REFERENCES identities (tenant_id, id)
);

CREATE TABLE access_request_lines (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  batch_id TEXT NOT NULL,
  catalog_item_id TEXT NOT NULL,
  group_id BIGINT NOT NULL,
  beneficiary_id BIGINT NOT NULL,
  account_id BIGINT NOT NULL,
  requested_by TEXT NOT NULL,
  justification TEXT NOT NULL,
  duration_hours DOUBLE PRECISION CHECK (duration_hours IS NULL OR duration_hours > 0),
  status TEXT NOT NULL CHECK (status IN ('pending','approved','denied','cancelled','expired','removed')),
  requested_at TEXT NOT NULL,
  decided_by TEXT,
  decided_at TEXT,
  decision_reason TEXT,
  edge_id BIGINT,
  expires_at TEXT,
  closed_at TEXT,
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, catalog_item_id) REFERENCES catalog_items (tenant_id, id),
  FOREIGN KEY (tenant_id, group_id) REFERENCES groups (tenant_id, id),
  FOREIGN KEY (tenant_id, beneficiary_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, account_id) REFERENCES accounts (tenant_id, id),
  FOREIGN KEY (tenant_id, requested_by) REFERENCES platform_users (tenant_id, id)
);

CREATE INDEX ix_request_lines_tenant_status ON access_request_lines (tenant_id, status);
CREATE INDEX ix_request_lines_tenant_requester ON access_request_lines (tenant_id, requested_by);
CREATE INDEX ix_request_lines_tenant_beneficiary ON access_request_lines (tenant_id, beneficiary_id);
CREATE INDEX ix_request_lines_tenant_batch ON access_request_lines (tenant_id, batch_id);
CREATE UNIQUE INDEX ux_request_lines_open ON access_request_lines (tenant_id, beneficiary_id, group_id)
  WHERE status IN ('pending','approved');

CREATE TABLE access_request_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  line_id TEXT NOT NULL,
  event TEXT NOT NULL CHECK (event IN ('submitted','approved','denied','cancelled','expired','removed')),
  actor_user_id TEXT,
  actor TEXT NOT NULL,
  note TEXT,
  at TEXT NOT NULL,
  FOREIGN KEY (tenant_id, line_id) REFERENCES access_request_lines (tenant_id, id)
);

CREATE INDEX ix_request_events_tenant_line ON access_request_events (tenant_id, line_id);

CREATE TRIGGER access_request_events_no_update BEFORE UPDATE ON access_request_events
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('access_request_events is append-only');

CREATE TRIGGER access_request_events_no_delete BEFORE DELETE ON access_request_events
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('access_request_events is append-only');

-- A line naming another tenant's catalog item is refused as a cross-tenant
-- reference before the open-line unique index can answer first (SQLite's
-- BEFORE trigger order; the composite foreign key above still backs it).
CREATE TRIGGER tg_access_request_lines_item_xtenant BEFORE INSERT OR UPDATE OF tenant_id, catalog_item_id ON access_request_lines
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('catalog_items', 'catalog_item_id', 'text');

-- Columns that name a user (or an edge that may expire) but are not foreign keys: SQLite never
-- enforced them, and they hold display strings or ids of rows that may be gone. The guard refuses an
-- id that belongs to ANOTHER tenant and tolerates one that does not exist (tessera_guard_soft_ref).
CREATE TRIGGER tg_catalog_items_updated_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, updated_by ON catalog_items
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'updated_by', 'text');
CREATE TRIGGER tg_access_request_lines_edge_id_xtenant BEFORE INSERT OR UPDATE OF tenant_id, edge_id ON access_request_lines
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('grant_edges', 'edge_id', 'bigint');
CREATE TRIGGER tg_access_request_lines_decided_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, decided_by ON access_request_lines
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'decided_by', 'text');
CREATE TRIGGER tg_access_request_events_actor_user_id_xtenant BEFORE INSERT OR UPDATE OF tenant_id, actor_user_id ON access_request_events
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'actor_user_id', 'text');
