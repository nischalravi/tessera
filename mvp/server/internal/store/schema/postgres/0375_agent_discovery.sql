CREATE TABLE agent_profiles (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  source TEXT NOT NULL,
  external_id TEXT NOT NULL,
  identity_id BIGINT NOT NULL,
  kind TEXT NOT NULL,
  creator_ref TEXT NOT NULL DEFAULT '',
  creator_identity_id BIGINT,
  sponsor_ref TEXT NOT NULL DEFAULT '',
  sponsor_identity_id BIGINT,
  first_seen_at TEXT NOT NULL,
  last_seen_at TEXT NOT NULL,
  PRIMARY KEY (tenant_id, source, external_id),
  FOREIGN KEY (tenant_id, identity_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, creator_identity_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, sponsor_identity_id) REFERENCES identities (tenant_id, id)
);
CREATE INDEX ix_agent_profiles_tenant_identity ON agent_profiles (tenant_id, identity_id);

CREATE TABLE mcp_findings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  source TEXT NOT NULL,
  kind TEXT NOT NULL,
  org TEXT NOT NULL,
  repo TEXT NOT NULL,
  path TEXT NOT NULL,
  location TEXT NOT NULL,
  server TEXT NOT NULL DEFAULT '',
  transport TEXT NOT NULL DEFAULT '',
  target TEXT NOT NULL DEFAULT '',
  secret_type TEXT NOT NULL DEFAULT '',
  fingerprint TEXT NOT NULL DEFAULT '',
  owner_ref TEXT NOT NULL DEFAULT '',
  owner_source TEXT NOT NULL DEFAULT 'none',
  owner_identity_id BIGINT,
  commit_sha TEXT NOT NULL DEFAULT '',
  first_seen_at TEXT NOT NULL,
  last_seen_at TEXT NOT NULL,
  UNIQUE (tenant_id, source, kind, org, repo, path, location, fingerprint),
  FOREIGN KEY (tenant_id, owner_identity_id) REFERENCES identities (tenant_id, id)
);
CREATE INDEX ix_mcp_findings_tenant_source ON mcp_findings (tenant_id, source);
