CREATE TABLE mcp_resources (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  resource TEXT NOT NULL,
  name TEXT NOT NULL,
  secret_hash TEXT NOT NULL CHECK (length(secret_hash) = 64),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','disabled')),
  created_by TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX ux_mcp_resources_uri ON mcp_resources (tenant_id, resource);

-- A client identified by a Client ID Metadata Document URL. The row is the
-- cache of the validated document (fetched through internal/safehttp) and the
-- admin's decision: a client is unusable until bound to an ai_agent identity
-- (the agent ceiling) and activated.
CREATE TABLE mcp_clients (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  client_id TEXT NOT NULL,
  client_name TEXT NOT NULL,
  redirect_uris TEXT NOT NULL,
  jwks TEXT NOT NULL DEFAULT '{"keys":[]}',
  agent_identity_id BIGINT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','active','disabled')),
  doc_sha256 TEXT NOT NULL,
  fetched_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  FOREIGN KEY (tenant_id, agent_identity_id) REFERENCES identities (tenant_id, id)
);
CREATE UNIQUE INDEX ux_mcp_clients_client_id ON mcp_clients (tenant_id, client_id);

-- A pending authorization request, then its single-use code (code_hash).
CREATE TABLE mcp_auth_requests (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  client_id TEXT NOT NULL,
  redirect_uri TEXT NOT NULL,
  state TEXT NOT NULL DEFAULT '',
  code_challenge TEXT NOT NULL,
  resource TEXT NOT NULL,
  scope TEXT NOT NULL,
  user_identity_id BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','denied','redeemed')),
  code_hash TEXT,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  FOREIGN KEY (tenant_id, user_identity_id) REFERENCES identities (tenant_id, id)
);
CREATE UNIQUE INDEX ux_mcp_auth_requests_code ON mcp_auth_requests (tenant_id, code_hash) WHERE code_hash IS NOT NULL;

-- An issued access token (the JWT itself is not stored). Introspection and
-- the kill switch work on this table.
CREATE TABLE mcp_tokens (
  jti TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  client_id TEXT NOT NULL,
  subject_identity_id BIGINT NOT NULL,
  agent_identity_id BIGINT NOT NULL,
  audience TEXT NOT NULL,
  scope TEXT NOT NULL,
  act TEXT NOT NULL,
  grant_type TEXT NOT NULL CHECK (grant_type IN ('authorization_code','token_exchange')),
  policy_version TEXT NOT NULL,
  issued_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  revoked_at TEXT,
  revoked_reason TEXT NOT NULL DEFAULT '',
  FOREIGN KEY (tenant_id, subject_identity_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, agent_identity_id) REFERENCES identities (tenant_id, id)
);
CREATE INDEX ix_mcp_tokens_agent ON mcp_tokens (tenant_id, agent_identity_id, revoked_at);
CREATE INDEX ix_mcp_tokens_subject ON mcp_tokens (tenant_id, subject_identity_id, revoked_at);

-- Every issue, exchange, denial and tool-call decision, with the policy
-- version. Identity ids are plain history (no foreign key: the log outlives
-- the identity).
CREATE TABLE mcp_decisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  at TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('issue','exchange','tool_call','revoke')),
  decision TEXT NOT NULL CHECK (decision IN ('allow','deny')),
  reason TEXT NOT NULL DEFAULT '',
  jti TEXT NOT NULL DEFAULT '',
  client_id TEXT NOT NULL DEFAULT '',
  subject_identity_id BIGINT,
  agent_identity_id BIGINT,
  resource TEXT NOT NULL DEFAULT '',
  tool TEXT NOT NULL DEFAULT '',
  requested_scope TEXT NOT NULL DEFAULT '',
  granted_scope TEXT NOT NULL DEFAULT '',
  policy_version TEXT NOT NULL
);
CREATE INDEX ix_mcp_decisions_at ON mcp_decisions (tenant_id, id);

-- A client's actor assertion may be used once.
CREATE TABLE mcp_actor_jtis (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  jti_hash TEXT NOT NULL CHECK (length(jti_hash) = 64),
  expires_at TEXT NOT NULL,
  PRIMARY KEY (tenant_id, jti_hash)
);
