-- Postgres dialect of schema/0350_review_populations.sql (Phase 0 PR14 dialect, kept in parity with the SQLite file
-- by TestSchemaParity_SQLiteAndPostgres). Cross-tenant guard triggers become composite
-- foreign keys (tenant_id, x_id) -> (tenant_id, id); see 0001_tenancy.sql. edge_id names a grant edge
-- without a foreign key (an edge is deleted when a review revokes it; the population keeps its id).

-- +goose Up

CREATE TABLE review_populations (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  campaign_id BIGINT NOT NULL,
  created_at TEXT NOT NULL,
  population_hash TEXT NOT NULL,
  item_count BIGINT NOT NULL,
  system_counts TEXT NOT NULL,
  source_syncs TEXT NOT NULL,
  scope TEXT NOT NULL,
  rules_version TEXT NOT NULL,
  qa_sample_pct BIGINT NOT NULL,
  PRIMARY KEY (tenant_id, campaign_id),
  FOREIGN KEY (tenant_id, campaign_id) REFERENCES review_campaigns (tenant_id, id)
);

CREATE TABLE review_population_rows (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  campaign_id BIGINT NOT NULL,
  ordinal BIGINT NOT NULL CHECK (ordinal >= 1),
  edge_id BIGINT NOT NULL,
  identity_id BIGINT NOT NULL,
  identity_ref TEXT NOT NULL,
  account_ref TEXT NOT NULL,
  system TEXT NOT NULL,
  entitlement TEXT NOT NULL,
  edge_src TEXT NOT NULL,
  edge_dst TEXT NOT NULL,
  in_scope_reason TEXT NOT NULL,
  disposition TEXT NOT NULL CHECK (disposition IN ('review','auto_certified')),
  PRIMARY KEY (tenant_id, campaign_id, ordinal),
  FOREIGN KEY (tenant_id, campaign_id) REFERENCES review_campaigns (tenant_id, id),
  FOREIGN KEY (tenant_id, identity_id) REFERENCES identities (tenant_id, id)
);
CREATE INDEX ix_review_population_rows_edge ON review_population_rows (tenant_id, campaign_id, edge_id);

CREATE TABLE review_auto_decisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  campaign_id BIGINT NOT NULL,
  ordinal BIGINT NOT NULL,
  edge_id BIGINT NOT NULL,
  identity_id BIGINT NOT NULL,
  decided_by_rule TEXT NOT NULL,
  qa_sample BIGINT NOT NULL DEFAULT 0 CHECK (qa_sample IN (0,1)),
  qa_reviewer_id BIGINT,
  qa_decision TEXT CHECK (qa_decision IN ('keep','revoke')),
  qa_comment TEXT,
  qa_decided_at TEXT,
  qa_decided_by_user_id TEXT,
  overturned BIGINT NOT NULL DEFAULT 0 CHECK (overturned IN (0,1)),
  UNIQUE (tenant_id, campaign_id, ordinal),
  FOREIGN KEY (tenant_id, campaign_id) REFERENCES review_campaigns (tenant_id, id),
  FOREIGN KEY (tenant_id, identity_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, qa_reviewer_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, qa_decided_by_user_id) REFERENCES platform_users (tenant_id, id)
);
CREATE INDEX ix_review_auto_decisions_campaign ON review_auto_decisions (tenant_id, campaign_id);

CREATE TABLE tenant_settings (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  key TEXT NOT NULL CHECK (length(key) BETWEEN 1 AND 64),
  value TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY (tenant_id, key)
);

-- Immutability: a frozen population never changes (the audit ledger's
-- append-only pattern, schema/0004_audit.sql).
CREATE TRIGGER review_populations_no_update BEFORE UPDATE ON review_populations
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('review_populations is immutable');
CREATE TRIGGER review_populations_no_delete BEFORE DELETE ON review_populations
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('review_populations is immutable');
CREATE TRIGGER review_population_rows_no_update BEFORE UPDATE ON review_population_rows
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('review_population_rows is immutable');
CREATE TRIGGER review_population_rows_no_delete BEFORE DELETE ON review_population_rows
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('review_population_rows is immutable');

-- An auto-decision keeps its rule and sample flag forever; a QA decision is
-- recorded once.
CREATE TRIGGER review_auto_decisions_core_immutable BEFORE UPDATE OF tenant_id, campaign_id, ordinal, edge_id, identity_id, decided_by_rule, qa_sample, qa_reviewer_id ON review_auto_decisions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('review_auto_decisions core fields are immutable');
CREATE TRIGGER review_auto_decisions_qa_once BEFORE UPDATE OF qa_decision ON review_auto_decisions
	FOR EACH ROW WHEN (OLD.qa_decision IS NOT NULL)
	EXECUTE FUNCTION tessera_abort('review_auto_decisions QA decision already recorded');
CREATE TRIGGER review_auto_decisions_no_delete BEFORE DELETE ON review_auto_decisions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('review_auto_decisions is append-only');
