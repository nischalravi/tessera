CREATE TABLE workflows (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  name TEXT NOT NULL,
  scope TEXT NOT NULL CHECK (scope IN ('access','service_account')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','retired')),
  version BIGINT NOT NULL DEFAULT 1 CHECK (version >= 1),
  created_at TEXT NOT NULL,
  updated_by TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, name)
);

CREATE TABLE workflow_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  workflow_id TEXT NOT NULL,
  version BIGINT NOT NULL CHECK (version >= 1),
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  definition TEXT NOT NULL CHECK (definition IS JSON),
  created_by TEXT NOT NULL,
  created_at TEXT NOT NULL,
  UNIQUE (tenant_id, workflow_id, version),
  FOREIGN KEY (tenant_id, workflow_id) REFERENCES workflows (tenant_id, id)
);

CREATE TRIGGER workflow_versions_no_update BEFORE UPDATE ON workflow_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('workflow_versions is append-only');

CREATE TRIGGER workflow_versions_no_delete BEFORE DELETE ON workflow_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('workflow_versions is append-only');

CREATE TABLE workflow_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  workflow_id TEXT NOT NULL,
  target_kind TEXT NOT NULL CHECK (target_kind IN ('catalog_item','request_type')),
  target_id TEXT NOT NULL,
  UNIQUE (tenant_id, target_kind, target_id),
  FOREIGN KEY (tenant_id, workflow_id) REFERENCES workflows (tenant_id, id)
);

CREATE INDEX ix_workflow_assignments_tenant_w ON workflow_assignments (tenant_id, workflow_id);
