CREATE TABLE identity_lifecycle (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  identity_id BIGINT NOT NULL,
  worker_type TEXT NOT NULL CHECK (worker_type IN ('employee','contractor','intern','partner','vendor','guest')),
  sponsor_identity_id BIGINT,
  organization TEXT,
  starts_at TEXT,
  ends_at TEXT,
  warned_days BIGINT,
  ended_at TEXT,
  source TEXT NOT NULL DEFAULT 'manual' CHECK (source IN ('manual','hris','sponsorship')),
  updated_by TEXT,
  updated_at TEXT NOT NULL,
  UNIQUE (tenant_id, identity_id),
  CHECK (worker_type = 'employee' OR ends_at IS NOT NULL),
  CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at),
  FOREIGN KEY (tenant_id, identity_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, sponsor_identity_id) REFERENCES identities (tenant_id, id)
);

CREATE INDEX ix_identity_lifecycle_tenant_ends ON identity_lifecycle (tenant_id, ends_at);
CREATE INDEX ix_identity_lifecycle_tenant_sponsor ON identity_lifecycle (tenant_id, sponsor_identity_id);

CREATE TABLE identity_lifecycle_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  identity_id BIGINT NOT NULL,
  event TEXT NOT NULL CHECK (event IN ('set','extended','converted','warned','ended')),
  worker_type TEXT,
  ends_at TEXT,
  note TEXT,
  actor_user_id TEXT,
  actor TEXT NOT NULL,
  at TEXT NOT NULL,
  FOREIGN KEY (tenant_id, identity_id) REFERENCES identities (tenant_id, id)
);

CREATE INDEX ix_lifecycle_events_tenant_identity ON identity_lifecycle_events (tenant_id, identity_id);

CREATE TRIGGER identity_lifecycle_events_no_update BEFORE UPDATE ON identity_lifecycle_events
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('identity_lifecycle_events is append-only');

CREATE TRIGGER identity_lifecycle_events_no_delete BEFORE DELETE ON identity_lifecycle_events
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('identity_lifecycle_events is append-only');

-- Columns that name a user (or an edge that may expire) but are not foreign keys: SQLite never
-- enforced them, and they hold display strings or ids of rows that may be gone. The guard refuses an
-- id that belongs to ANOTHER tenant and tolerates one that does not exist (tessera_guard_soft_ref).
CREATE TRIGGER tg_identity_lifecycle_updated_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, updated_by ON identity_lifecycle
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'updated_by', 'text');
CREATE TRIGGER tg_identity_lifecycle_events_actor_user_id_xtenant BEFORE INSERT OR UPDATE OF tenant_id, actor_user_id ON identity_lifecycle_events
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'actor_user_id', 'text');
