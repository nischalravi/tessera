CREATE TABLE intake_records (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  channel TEXT NOT NULL CHECK (channel IN ('sponsor_invite','bulk_invite','self_registration','sis','hris','vms',
    'partner_invite','partner_scim')),
  match_mode TEXT NOT NULL CHECK (match_mode IN ('authoritative','self_asserted','federated')),
  source_record_id TEXT,
  submitted_by TEXT,
  sponsor_identity_id BIGINT,
  batch_id TEXT,
  status TEXT NOT NULL CHECK (status IN ('received','matching','review','resolved','rejected')),
  invitation_status TEXT NOT NULL DEFAULT 'ready' CHECK (invitation_status IN ('ready','sent','claimed','revoked','expired')),
  -- the claimant's own statement at the claim page's "do you already have an
  -- account?" question (GU-6): recorded for the review queue, never used to link (K3)
  existing_account TEXT CHECK (existing_account IN ('yes','no')),
  existing_account_at TEXT,
  claimed_at TEXT,
  created_at TEXT NOT NULL,
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, source_record_id) REFERENCES identity_source_records (tenant_id, id),
  FOREIGN KEY (tenant_id, sponsor_identity_id) REFERENCES identities (tenant_id, id)
);

CREATE INDEX ix_intake_records_sponsor ON intake_records (tenant_id, sponsor_identity_id, created_at);

CREATE TABLE sponsorships (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  guest_identity_id BIGINT NOT NULL,
  intake_id TEXT NOT NULL,
  sponsor_identity_id BIGINT NOT NULL,
  population TEXT NOT NULL CHECK (population IN ('visitor','contractor','volunteer','partner')),
  purpose TEXT NOT NULL CHECK (purpose <> ''),
  access_bundle TEXT NOT NULL DEFAULT '[]',
  required_ial BIGINT NOT NULL CHECK (required_ial IN (0,1,2)),
  required_aal BIGINT NOT NULL CHECK (required_aal IN (1,2,3)),
  starts_at TEXT NOT NULL,
  ends_at TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('requested','pending_approval','active','transfer_pending','ended',
    'revoked','rejected')),
  policy_version TEXT NOT NULL CHECK (policy_version <> ''),
  approved_by TEXT,
  approved_at TEXT,
  transfer_to_identity_id BIGINT,
  transfer_deadline TEXT,
  created_by TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  ended_at TEXT,
  end_reason TEXT,
  UNIQUE (tenant_id, id),
  CHECK (ends_at > starts_at),
  CHECK (guest_identity_id <> sponsor_identity_id),
  CHECK ((transfer_to_identity_id IS NULL) = (transfer_deadline IS NULL)),
  CHECK ((status = 'transfer_pending') = (transfer_to_identity_id IS NOT NULL)),
  CHECK ((status IN ('ended','revoked','rejected')) = (ended_at IS NOT NULL)),
  FOREIGN KEY (tenant_id, guest_identity_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, intake_id) REFERENCES intake_records (tenant_id, id),
  FOREIGN KEY (tenant_id, sponsor_identity_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, transfer_to_identity_id) REFERENCES identities (tenant_id, id)
);

CREATE INDEX ix_sponsorships_sponsor ON sponsorships (tenant_id, sponsor_identity_id, status);
CREATE INDEX ix_sponsorships_guest ON sponsorships (tenant_id, guest_identity_id, status);
CREATE INDEX ix_sponsorships_status_ends ON sponsorships (tenant_id, status, ends_at);

CREATE TABLE sponsorship_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  sponsorship_id TEXT NOT NULL,
  event TEXT NOT NULL CHECK (event IN ('created','approval_requested','approved','rejected','renewed','ended',
    'revoked','expired','transfer_requested','transfer_accepted','transfer_expired')),
  from_status TEXT,
  to_status TEXT NOT NULL,
  note TEXT,
  policy_version TEXT NOT NULL CHECK (policy_version <> ''),
  actor_user_id TEXT,
  actor TEXT NOT NULL,
  at TEXT NOT NULL,
  FOREIGN KEY (tenant_id, sponsorship_id) REFERENCES sponsorships (tenant_id, id)
);

CREATE INDEX ix_sponsorship_events_sponsorship ON sponsorship_events (tenant_id, sponsorship_id, id);

CREATE TRIGGER sponsorship_events_no_update BEFORE UPDATE ON sponsorship_events
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('sponsorship_events is append-only');

CREATE TRIGGER sponsorship_events_no_delete BEFORE DELETE ON sponsorship_events
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('sponsorship_events is append-only');

-- A sponsorship's person, intake and term never change; its sponsor changes
-- only through a transfer, its status only forward (a final status is final).
CREATE TRIGGER sponsorships_immutable BEFORE UPDATE ON sponsorships
	FOR EACH ROW WHEN (OLD.status IN ('ended','revoked','rejected') OR NEW.id <> OLD.id OR NEW.tenant_id <> OLD.tenant_id
		OR NEW.guest_identity_id <> OLD.guest_identity_id OR NEW.intake_id <> OLD.intake_id
		OR NEW.population <> OLD.population OR NEW.starts_at <> OLD.starts_at OR NEW.created_at <> OLD.created_at)
	EXECUTE FUNCTION tessera_abort('sponsorships: final rows and identity columns are immutable');

CREATE TRIGGER sponsorships_no_delete BEFORE DELETE ON sponsorships
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('sponsorships are append-only');

CREATE TRIGGER intake_records_immutable BEFORE UPDATE ON intake_records
	FOR EACH ROW WHEN (NEW.id <> OLD.id OR NEW.tenant_id <> OLD.tenant_id OR NEW.channel <> OLD.channel OR NEW.match_mode <> OLD.match_mode
		OR NEW.created_at <> OLD.created_at)
	EXECUTE FUNCTION tessera_abort('intake_records: channel, match mode and identity columns are immutable');

CREATE TRIGGER intake_records_no_delete BEFORE DELETE ON intake_records
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('intake_records are append-only');

-- Columns that name a user (or an edge that may expire) but are not foreign keys: SQLite never
-- enforced them, and they hold display strings or ids of rows that may be gone. The guard refuses an
-- id that belongs to ANOTHER tenant and tolerates one that does not exist (tessera_guard_soft_ref).
CREATE TRIGGER tg_intake_records_submitted_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, submitted_by ON intake_records
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'submitted_by', 'text');
CREATE TRIGGER tg_sponsorships_created_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, created_by ON sponsorships
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'created_by', 'text');
CREATE TRIGGER tg_sponsorships_approved_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, approved_by ON sponsorships
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'approved_by', 'text');
CREATE TRIGGER tg_sponsorship_events_actor_user_id_xtenant BEFORE INSERT OR UPDATE OF tenant_id, actor_user_id ON sponsorship_events
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'actor_user_id', 'text');
