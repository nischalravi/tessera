CREATE TABLE intended_grants (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  identity_id BIGINT NOT NULL,
  account_id BIGINT,
  target_kind TEXT NOT NULL CHECK (target_kind IN ('group','perm')),
  target_system TEXT NOT NULL,
  target_ref TEXT NOT NULL,
  provenance TEXT NOT NULL CHECK (provenance IN ('request','role','birthright','jit','review_keep','manual')),
  provenance_ref TEXT,
  edge_id BIGINT,
  valid_from TEXT NOT NULL,
  valid_until TEXT,
  owner_identity_id BIGINT,
  created_at TEXT NOT NULL,
  closed_at TEXT,
  close_reason TEXT,
  UNIQUE (tenant_id, id),
  CHECK ((closed_at IS NULL) = (close_reason IS NULL)),
  FOREIGN KEY (tenant_id, identity_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, account_id) REFERENCES accounts (tenant_id, id),
  FOREIGN KEY (tenant_id, owner_identity_id) REFERENCES identities (tenant_id, id)
);
CREATE UNIQUE INDEX ux_intended_grants_open ON intended_grants (tenant_id, identity_id, target_kind, target_system, target_ref) WHERE closed_at IS NULL;
CREATE INDEX ix_intended_grants_edge ON intended_grants (tenant_id, edge_id);
CREATE INDEX ix_intended_grants_target ON intended_grants (tenant_id, target_system, target_ref);

CREATE TABLE observed_runs (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  system TEXT NOT NULL,
  source TEXT NOT NULL CHECK (source IN ('connector','backfill')),
  observed_at TEXT NOT NULL,
  entitlements BIGINT NOT NULL DEFAULT 0,
  UNIQUE (tenant_id, id)
);
CREATE INDEX ix_observed_runs_system ON observed_runs (tenant_id, system, observed_at);

CREATE TABLE observed_entitlements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  system TEXT NOT NULL,
  account_ref TEXT NOT NULL,
  account_id BIGINT,
  identity_id BIGINT,
  entitlement_kind TEXT NOT NULL CHECK (entitlement_kind IN ('group','perm')),
  entitlement_system TEXT NOT NULL,
  entitlement_ref TEXT NOT NULL,
  run_id TEXT NOT NULL,
  observed_at TEXT NOT NULL,
  UNIQUE (tenant_id, system, account_ref, entitlement_kind, entitlement_system, entitlement_ref),
  FOREIGN KEY (tenant_id, account_id) REFERENCES accounts (tenant_id, id),
  FOREIGN KEY (tenant_id, identity_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, run_id) REFERENCES observed_runs (tenant_id, id)
);
CREATE INDEX ix_observed_entitlements_run ON observed_entitlements (tenant_id, system, run_id);
CREATE INDEX ix_observed_entitlements_ent ON observed_entitlements (tenant_id, entitlement_system, entitlement_ref);
