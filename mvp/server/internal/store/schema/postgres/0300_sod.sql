-- Postgres dialect of schema/0300_sod.sql (kept in parity with the SQLite file by
-- TestSchemaParity_SQLiteAndPostgres). Cross-tenant guard triggers become composite
-- foreign keys (tenant_id, x_id) -> (tenant_id, id); see 0001_tenancy.sql.

-- +goose Up

CREATE TABLE sod_functions (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  key TEXT NOT NULL,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  owner_identity_id BIGINT,
  selectors TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','retired')),
  version BIGINT NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_by TEXT,
  updated_at TEXT NOT NULL,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, key),
  UNIQUE (tenant_id, name),
  FOREIGN KEY (tenant_id, owner_identity_id) REFERENCES identities (tenant_id, id)
);

CREATE TABLE sod_rulesets (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  key TEXT NOT NULL,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  enabled BIGINT NOT NULL DEFAULT 1 CHECK (enabled IN (0,1)),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','retired')),
  version BIGINT NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_by TEXT,
  updated_at TEXT NOT NULL,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, key),
  UNIQUE (tenant_id, name)
);

CREATE TABLE sod_risks (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  key TEXT NOT NULL,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  priority TEXT NOT NULL CHECK (priority IN ('critical','high','medium','low')),
  business_process TEXT NOT NULL DEFAULT '',
  owner_identity_id BIGINT,
  ruleset_id TEXT NOT NULL,
  subjects TEXT NOT NULL DEFAULT '{}',
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','retired')),
  version BIGINT NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_by TEXT,
  updated_at TEXT NOT NULL,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, key),
  UNIQUE (tenant_id, name),
  FOREIGN KEY (tenant_id, owner_identity_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, ruleset_id) REFERENCES sod_rulesets (tenant_id, id)
);
CREATE INDEX ix_sod_risks_tenant_ruleset ON sod_risks (tenant_id, ruleset_id);

CREATE TABLE sod_risk_functions (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  risk_id TEXT NOT NULL,
  function_id TEXT NOT NULL,
  ord BIGINT NOT NULL,
  PRIMARY KEY (tenant_id, risk_id, function_id),
  FOREIGN KEY (tenant_id, risk_id) REFERENCES sod_risks (tenant_id, id),
  FOREIGN KEY (tenant_id, function_id) REFERENCES sod_functions (tenant_id, id)
);
CREATE INDEX ix_sod_risk_functions_tenant_function ON sod_risk_functions (tenant_id, function_id);

CREATE TABLE sod_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  kind TEXT NOT NULL CHECK (kind IN ('function','risk','ruleset')),
  object_id TEXT NOT NULL,
  version BIGINT NOT NULL,
  snapshot TEXT NOT NULL,
  note TEXT,
  changed_by TEXT,
  actor TEXT NOT NULL,
  changed_at TEXT NOT NULL,
  UNIQUE (tenant_id, kind, object_id, version)
);

CREATE TRIGGER sod_versions_no_update BEFORE UPDATE ON sod_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('sod_versions is append-only');

CREATE TRIGGER sod_versions_no_delete BEFORE DELETE ON sod_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('sod_versions is append-only');

-- object_id names a function, risk or ruleset by kind, with no foreign key; the guard refuses an
-- object of ANOTHER tenant and tolerates one that does not exist, like SQLite.
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION tessera_guard_sod_versions() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $fn$
DECLARE
	crosses boolean;
BEGIN
	EXECUTE format('SELECT EXISTS (SELECT 1 FROM %I p WHERE p.id = $1 AND p.tenant_id <> $2)',
		CASE NEW.kind WHEN 'function' THEN 'sod_functions' WHEN 'risk' THEN 'sod_risks' ELSE 'sod_rulesets' END)
		INTO crosses USING NEW.object_id, NEW.tenant_id;
	IF crosses THEN
		RAISE EXCEPTION 'cross-tenant reference: sod_versions' USING ERRCODE = 'integrity_constraint_violation';
	END IF;
	RETURN NEW;
END
$fn$;
-- +goose StatementEnd

CREATE TRIGGER tg_sod_versions_object_xtenant BEFORE INSERT OR UPDATE OF tenant_id, kind, object_id ON sod_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_sod_versions();

