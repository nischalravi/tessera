CREATE TABLE edge_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  edge_id BIGINT,
  src TEXT NOT NULL, dst TEXT NOT NULL, relation TEXT NOT NULL, source TEXT NOT NULL,
  expires_at TEXT, valid_from TEXT NOT NULL, valid_to TEXT
);
CREATE INDEX ix_edge_history_tenant_open ON edge_history (tenant_id, src, dst, valid_to);
CREATE INDEX ix_edge_history_tenant_from ON edge_history (tenant_id, valid_from);

CREATE TRIGGER tg_edge_history_frozen BEFORE UPDATE OF edge_id, relation, source, valid_from, expires_at ON edge_history
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('edge_history: a span is closed, not edited');

INSERT INTO edge_history (tenant_id, edge_id, src, dst, relation, source, expires_at, valid_from)
SELECT e.tenant_id, e.id, e.src, e.dst, e.relation, e.source, e.expires_at, e.created_at
FROM grant_edges e
WHERE NOT EXISTS (SELECT 1 FROM edge_history h WHERE h.tenant_id = e.tenant_id AND h.src = e.src AND h.dst = e.dst
	AND h.valid_to IS NULL);
