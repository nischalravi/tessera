-- review_item_roles has a composite foreign key to review_items, which needs this key on the parent.
ALTER TABLE review_items ADD UNIQUE (tenant_id, id);

CREATE TABLE business_role_exclusions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  role_id TEXT NOT NULL,
  identity_id BIGINT NOT NULL,
  reason TEXT NOT NULL,
  version BIGINT NOT NULL,
  excluded_by TEXT,
  excluded_actor TEXT NOT NULL,
  excluded_at TEXT NOT NULL,
  review_item_id BIGINT,
  removed_at TEXT,
  removed_version BIGINT,
  removed_by TEXT,
  removed_reason TEXT,
  UNIQUE (tenant_id, role_id, version),
  FOREIGN KEY (tenant_id, role_id) REFERENCES business_roles (tenant_id, id),
  FOREIGN KEY (tenant_id, identity_id) REFERENCES identities (tenant_id, id),
  FOREIGN KEY (tenant_id, excluded_by) REFERENCES platform_users (tenant_id, id),
  FOREIGN KEY (tenant_id, removed_by) REFERENCES platform_users (tenant_id, id),
  FOREIGN KEY (tenant_id, review_item_id) REFERENCES review_items (tenant_id, id)
);

CREATE UNIQUE INDEX ux_role_exclusions_active ON business_role_exclusions (tenant_id, role_id, identity_id)
  WHERE removed_at IS NULL;

CREATE TRIGGER business_role_exclusions_no_delete BEFORE DELETE ON business_role_exclusions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('business_role_exclusions is append-only');

CREATE TABLE review_item_roles (
  item_id BIGINT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  role_id TEXT NOT NULL,
  member_source TEXT NOT NULL CHECK (member_source IN ('rule','request','manual')),
  resolution TEXT CHECK (resolution IN ('unassign','exclude','flag')),
  resolved_at TEXT,
  FOREIGN KEY (tenant_id, item_id) REFERENCES review_items (tenant_id, id),
  FOREIGN KEY (tenant_id, role_id) REFERENCES business_roles (tenant_id, id)
);

CREATE INDEX ix_review_item_roles_tenant_role ON review_item_roles (tenant_id, role_id);

CREATE TABLE review_template_roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  template_id TEXT NOT NULL,
  role_id TEXT NOT NULL,
  UNIQUE (tenant_id, template_id, role_id),
  FOREIGN KEY (tenant_id, template_id) REFERENCES review_templates (tenant_id, id),
  FOREIGN KEY (tenant_id, role_id) REFERENCES business_roles (tenant_id, id)
);
