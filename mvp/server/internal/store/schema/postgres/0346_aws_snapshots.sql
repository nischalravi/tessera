-- Postgres dialect of schema/0320_aws_snapshots.sql (AWS evaluator PR-7, issue #26, kept in parity with the
-- SQLite file by TestSchemaParity_SQLiteAndPostgres). The cross-tenant guard triggers become
-- composite foreign keys (tenant_id, x_id) -> (tenant_id, id), which the (tenant_id, id) primary
-- keys of aws_snapshots and aws_policy_documents already allow; see 0001_tenancy.sql.

-- +goose Up

CREATE TABLE aws_connectors (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
  config TEXT NOT NULL CHECK (config IS JSON),
  external_id TEXT NOT NULL,
  credentials_enc BYTEA NOT NULL,
  status TEXT NOT NULL DEFAULT 'idle' CHECK (status IN ('idle','ok','failed')),
  last_snapshot_id TEXT,
  last_run_at TEXT,
  last_error TEXT NOT NULL DEFAULT '',
  created_by TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX ux_aws_connectors_name ON aws_connectors (tenant_id, name);

CREATE TABLE aws_snapshots (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  id TEXT NOT NULL,
  taken_at TEXT NOT NULL,
  org_id TEXT,
  account_ids TEXT NOT NULL CHECK (account_ids IS JSON),
  catalog_version TEXT NOT NULL,
  source TEXT NOT NULL CHECK (source IN ('connector', 'pr-sim', 'harness')),
  connector_id TEXT,
  PRIMARY KEY (tenant_id, id)
);
CREATE INDEX aws_snapshots_guard ON aws_snapshots (id);

CREATE TABLE aws_policy_documents (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  id TEXT NOT NULL,
  kind TEXT NOT NULL,
  source_arn TEXT NOT NULL,
  version_id TEXT,
  raw_json BYTEA NOT NULL,
  normalized TEXT NOT NULL CHECK (normalized IS JSON),
  fetched_at TEXT NOT NULL,
  PRIMARY KEY (tenant_id, id)
);
CREATE INDEX aws_policy_documents_source ON aws_policy_documents (tenant_id, source_arn);
CREATE INDEX aws_policy_documents_guard ON aws_policy_documents (id);

CREATE TABLE aws_policy_attachments (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id TEXT NOT NULL,
  policy_id TEXT NOT NULL,
  target_arn TEXT NOT NULL,
  attachment_type TEXT NOT NULL,
  via TEXT NOT NULL CHECK (via IS JSON),
  FOREIGN KEY (tenant_id, snapshot_id) REFERENCES aws_snapshots (tenant_id, id),
  FOREIGN KEY (tenant_id, policy_id) REFERENCES aws_policy_documents (tenant_id, id)
);
CREATE INDEX aws_policy_attachments_snapshot ON aws_policy_attachments (tenant_id, snapshot_id);
CREATE INDEX aws_policy_attachments_target ON aws_policy_attachments (tenant_id, target_arn);

CREATE TABLE aws_org_nodes (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  snapshot_id TEXT NOT NULL,
  id TEXT NOT NULL,
  kind TEXT NOT NULL,
  parent_id TEXT,
  name TEXT NOT NULL,
  PRIMARY KEY (tenant_id, snapshot_id, id),
  FOREIGN KEY (tenant_id, snapshot_id) REFERENCES aws_snapshots (tenant_id, id)
);

CREATE TABLE aws_snapshot_entities (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  snapshot_id TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('principal','resource','resource_policy','kms_grant','s3_bucket','vpce_policy','canonical_id',
    'identity_center','org')),
  key TEXT NOT NULL,
  body TEXT NOT NULL CHECK (body IS JSON),
  PRIMARY KEY (tenant_id, snapshot_id, kind, key),
  FOREIGN KEY (tenant_id, snapshot_id) REFERENCES aws_snapshots (tenant_id, id)
);

CREATE TABLE aws_collection_findings (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('policy_unparseable','statement_dropped','account_error')),
  source_arn TEXT NOT NULL,
  policy_kind TEXT NOT NULL DEFAULT '',
  code TEXT NOT NULL,
  detail TEXT NOT NULL,
  scope TEXT NOT NULL CHECK (scope IS JSON),
  FOREIGN KEY (tenant_id, snapshot_id) REFERENCES aws_snapshots (tenant_id, id)
);
CREATE INDEX aws_collection_findings_snapshot ON aws_collection_findings (tenant_id, snapshot_id);

CREATE TABLE aws_trust_edges (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id TEXT NOT NULL,
  from_arn TEXT NOT NULL,
  to_role_arn TEXT NOT NULL,
  mechanism TEXT NOT NULL,
  outcome TEXT NOT NULL,
  residual TEXT NOT NULL CHECK (residual IS JSON),
  explanation_id TEXT NOT NULL,
  FOREIGN KEY (tenant_id, snapshot_id) REFERENCES aws_snapshots (tenant_id, id)
);
CREATE INDEX aws_trust_edges_snapshot ON aws_trust_edges (tenant_id, snapshot_id);
CREATE INDEX aws_trust_edges_from ON aws_trust_edges (tenant_id, from_arn);
CREATE INDEX aws_trust_edges_to ON aws_trust_edges (tenant_id, to_role_arn);

CREATE TABLE aws_effective_permissions (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id TEXT NOT NULL,
  principal_arn TEXT NOT NULL,
  action_atom BIGINT NOT NULL,
  resource_atom BIGINT NOT NULL,
  outcome TEXT NOT NULL,
  residual TEXT CHECK (residual IS NULL OR residual IS JSON),
  fidelity TEXT NOT NULL,
  explanation_id TEXT NOT NULL,
  engine_version TEXT NOT NULL,
  catalog_version TEXT NOT NULL,
  FOREIGN KEY (tenant_id, snapshot_id) REFERENCES aws_snapshots (tenant_id, id)
);
CREATE INDEX aws_eff_snapshot ON aws_effective_permissions (tenant_id, snapshot_id);
CREATE INDEX aws_eff_principal ON aws_effective_permissions (tenant_id, principal_arn);
CREATE INDEX aws_eff_action ON aws_effective_permissions (tenant_id, action_atom);
CREATE INDEX aws_eff_resource ON aws_effective_permissions (tenant_id, resource_atom);

CREATE TABLE aws_explanations (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  id TEXT NOT NULL,
  trace TEXT NOT NULL CHECK (trace IS JSON),
  PRIMARY KEY (tenant_id, id)
);
