CREATE TABLE questionnaires (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  title TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','retired')),
  version BIGINT NOT NULL DEFAULT 1 CHECK (version >= 1),
  created_at TEXT NOT NULL,
  updated_by TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, title)
);

CREATE TABLE questionnaire_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  questionnaire_id TEXT NOT NULL,
  version BIGINT NOT NULL CHECK (version >= 1),
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  questions TEXT NOT NULL CHECK (questions IS JSON),
  created_by TEXT NOT NULL,
  created_at TEXT NOT NULL,
  UNIQUE (tenant_id, questionnaire_id, version),
  FOREIGN KEY (tenant_id, questionnaire_id) REFERENCES questionnaires (tenant_id, id)
);

CREATE TRIGGER questionnaire_versions_no_update BEFORE UPDATE ON questionnaire_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('questionnaire_versions is append-only');

CREATE TRIGGER questionnaire_versions_no_delete BEFORE DELETE ON questionnaire_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('questionnaire_versions is append-only');

CREATE TABLE questionnaire_attachments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  questionnaire_id TEXT NOT NULL,
  target_kind TEXT NOT NULL CHECK (target_kind IN ('catalog_item','business_role','review_campaign','privileged')),
  target_id TEXT NOT NULL,
  UNIQUE (tenant_id, target_kind, target_id),
  FOREIGN KEY (tenant_id, questionnaire_id) REFERENCES questionnaires (tenant_id, id)
);

CREATE INDEX ix_questionnaire_attachments_tenant_q ON questionnaire_attachments (tenant_id, questionnaire_id);

CREATE TABLE questionnaire_answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  questionnaire_id TEXT NOT NULL,
  version BIGINT NOT NULL,
  subject_kind TEXT NOT NULL CHECK (subject_kind IN ('request_line','role_request','review_item')),
  subject_id TEXT NOT NULL,
  answers TEXT NOT NULL CHECK (answers IS JSON),
  answers_hash TEXT NOT NULL,
  answered_by TEXT NOT NULL,
  answered_at TEXT NOT NULL,
  UNIQUE (tenant_id, subject_kind, subject_id, questionnaire_id),
  FOREIGN KEY (tenant_id, questionnaire_id) REFERENCES questionnaires (tenant_id, id),
  FOREIGN KEY (tenant_id, questionnaire_id, version) REFERENCES questionnaire_versions (tenant_id, questionnaire_id, version)
);
