-- See 0001_tenancy.sql.

-- +goose Up

CREATE TABLE review_item_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  item_id BIGINT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('consult','answer','reassign')),
  ref_id BIGINT,
  actor_user_id TEXT NOT NULL,
  actor TEXT NOT NULL,
  target_identity_id BIGINT,
  note TEXT NOT NULL CHECK (length(note) BETWEEN 1 AND 1000),
  at TEXT NOT NULL,
  FOREIGN KEY (item_id) REFERENCES review_items (id),
  FOREIGN KEY (tenant_id, actor_user_id) REFERENCES platform_users (tenant_id, id),
  FOREIGN KEY (tenant_id, target_identity_id) REFERENCES identities (tenant_id, id)
);
CREATE INDEX ix_review_item_events_tenant_item ON review_item_events (tenant_id, item_id, id);
CREATE INDEX ix_review_item_events_tenant_target ON review_item_events (tenant_id, target_identity_id, kind);

CREATE TRIGGER review_item_events_no_update BEFORE UPDATE ON review_item_events
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('review_item_events is append-only');
CREATE TRIGGER review_item_events_no_delete BEFORE DELETE ON review_item_events
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('review_item_events is append-only');

CREATE TRIGGER tg_review_item_events_item_xtenant BEFORE INSERT OR UPDATE OF tenant_id, item_id ON review_item_events
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('review_items', 'item_id', 'bigint');
