CREATE TABLE abac_policies (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  condition TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','retired')),
  version BIGINT NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_by TEXT,
  updated_at TEXT NOT NULL,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, name)
);

CREATE TABLE abac_policy_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  policy_id TEXT NOT NULL,
  version BIGINT NOT NULL,
  snapshot TEXT NOT NULL,
  note TEXT,
  changed_by TEXT,
  actor TEXT NOT NULL,
  changed_at TEXT NOT NULL,
  UNIQUE (tenant_id, policy_id, version),
  FOREIGN KEY (tenant_id, policy_id) REFERENCES abac_policies (tenant_id, id)
);

CREATE TABLE abac_bindings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  kind TEXT NOT NULL CHECK (kind IN ('catalog_item')),
  target_id TEXT NOT NULL,
  policy_id TEXT NOT NULL,
  bound_by TEXT,
  bound_at TEXT NOT NULL,
  UNIQUE (tenant_id, kind, target_id),
  FOREIGN KEY (tenant_id, policy_id) REFERENCES abac_policies (tenant_id, id)
);

CREATE INDEX ix_abac_bindings_tenant_policy ON abac_bindings (tenant_id, policy_id);

CREATE TRIGGER abac_policy_versions_no_update BEFORE UPDATE ON abac_policy_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('abac_policy_versions is append-only');

CREATE TRIGGER abac_policy_versions_no_delete BEFORE DELETE ON abac_policy_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('abac_policy_versions is append-only');

-- target_id names a catalog item (kind 'catalog_item') with no foreign key; the guard
-- refuses an item of ANOTHER tenant and tolerates one that does not exist, like SQLite.
CREATE TRIGGER tg_abac_bindings_target_xtenant BEFORE INSERT OR UPDATE OF tenant_id, kind, target_id ON abac_bindings
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('catalog_items', 'target_id', 'text');

-- Columns that name a user (or an edge that may expire) but are not foreign keys: SQLite never
-- enforced them, and they hold display strings or ids of rows that may be gone. The guard refuses an
-- id that belongs to ANOTHER tenant and tolerates one that does not exist (tessera_guard_soft_ref).
CREATE TRIGGER tg_abac_policies_updated_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, updated_by ON abac_policies
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'updated_by', 'text');
CREATE TRIGGER tg_abac_policy_versions_changed_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, changed_by ON abac_policy_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'changed_by', 'text');
CREATE TRIGGER tg_abac_bindings_bound_by_xtenant BEFORE INSERT OR UPDATE OF tenant_id, bound_by ON abac_bindings
	FOR EACH ROW EXECUTE FUNCTION tessera_guard_soft_ref('platform_users', 'bound_by', 'text');
