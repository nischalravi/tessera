CREATE TABLE policy_sources (
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  kind TEXT NOT NULL CHECK (kind IN ('invariant')),
  src_key TEXT NOT NULL CHECK (length(src_key) BETWEEN 1 AND 64),
  cedar TEXT NOT NULL CHECK (length(cedar) BETWEEN 1 AND 262144),
  sha256 TEXT NOT NULL CHECK (length(sha256) = 64),
  status TEXT NOT NULL CHECK (status IN ('active', 'disabled')),
  version BIGINT NOT NULL CHECK (version >= 1),
  policy_ref TEXT NOT NULL DEFAULT '',
  updated_by TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY (tenant_id, kind, src_key)
);

CREATE TABLE policy_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  kind TEXT NOT NULL,
  src_key TEXT NOT NULL,
  version BIGINT NOT NULL CHECK (version >= 1),
  cedar TEXT NOT NULL,
  sha256 TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('active', 'disabled')),
  policy_ref TEXT NOT NULL DEFAULT '',
  actor TEXT NOT NULL,
  at TEXT NOT NULL,
  FOREIGN KEY (tenant_id, kind, src_key) REFERENCES policy_sources (tenant_id, kind, src_key)
);
CREATE UNIQUE INDEX ux_policy_versions_source ON policy_versions (tenant_id, kind, src_key, version);

CREATE TRIGGER policy_versions_no_update BEFORE UPDATE ON policy_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('policy_versions is append-only');
CREATE TRIGGER policy_versions_no_delete BEFORE DELETE ON policy_versions
	FOR EACH ROW EXECUTE FUNCTION tessera_abort('policy_versions is append-only');
